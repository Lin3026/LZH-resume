/**
 * 方块颜色配置文件
 * =========================================
 * 编辑此文件来定义方块下落的顺序
 *
 * 颜色数值定义：
 *   0 = 红色 (Red)   - 数值: 10
 *   1 = 黄色 (Yellow) - 数值: 20
 *   2 = 绿色 (Green) - 数值: 30
 *   3 = 紫色 (Purple) - 数值: 40
 *
 * 数组元素：每个数字代表一个方块的颜色类型
 * 游戏进行时，新补充到顶部的方块会按此数组顺序循环取色
 *
 * 示例：
 *   [0, 1, 2, 3, 0, 0, 2, 1, 1, 2, 0, ...]
 *   表示：红→黄→绿→紫→红→红→绿→黄→黄→绿→红...
 *
 * 修改后保存，开发服务器会自动热更新
 */

/** 颜色类型对应的数值（用于计分、展示等） */
export const GEM_VALUES: Record<number, number> = {
  0: 10, // 红色
  1: 20, // 黄色
  2: 30, // 绿色
  3: 40, // 紫色
};

/** 颜色类型对应的名称 */
export const GEM_NAMES: Record<number, string> = {
  0: '红',
  1: '黄',
  2: '绿',
  3: '紫',
};

/**
 * 方块下落顺序配置
 * =============================
 * 修改此数组即可自定义下落顺序
 * 游戏会循环读取此数组（到末尾后从头开始）
 */
export const GEM_SEQUENCE: number[] = [
  // 初始序列 — 可按需修改
  0, 1, 2, 3, // 红、黄、绿、紫
  0, 0,        // 红、红
  1, 2,        // 黄、绿
  3, 2,        // 紫、绿
  2, 1, 0,    // 绿、黄、红
  1, 1,        // 黄、黄
  3, 3,        // 紫、紫
  0, 2, 1,    // 红、绿、黄
  0, 3,        // 红、紫
  1, 0, 2,    // 黄、红、绿
  2, 3,        // 绿、紫
  // 可继续往下添加...
];

/**
 * 从序列中读取下一个颜色类型
 * 内部维护一个索引，每次调用返回序列中的下一个值（循环）
 */
let seqIndex = 0;
export function nextGemType(): number {
  const type = GEM_SEQUENCE[seqIndex % GEM_SEQUENCE.length];
  seqIndex++;
  return type;
}

/** 重置序列索引（每次新游戏开始时调用） */
export function resetGemSequence(): void {
  seqIndex = 0;
}
